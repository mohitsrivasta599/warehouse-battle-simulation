GRID = 10
MAX_TEAM = 10
MOVES = np.array([
    [-1, 0], [1, 0], [0, -1], [0, 1], [0, 0]
])

def clip_pos(p):
    return np.clip(p, 0, GRID - 1).astype(int)

def distance(a, b):
    return int(abs(a[0] - b[0]) + abs(a[1] - b[1]))

class WarehouseBattle(gym.Env):
    def __init__(self, agents=5, enemies=5, random_counts=False):
        super().__init__()
        self.agent_setting = agents
        self.enemy_setting = enemies
        self.random_counts = random_counts
        self.max_steps = 50

        self.observation_space = spaces.Box(
            low=-1, high=1, shape=(43,), dtype=np.float32
        )
        self.action_space = spaces.MultiDiscrete(
            np.full(MAX_TEAM, 5, dtype=np.int64)
        )

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)

        if self.random_counts:
            self.na = int(self.np_random.integers(1, 11))
            self.ne = int(self.np_random.integers(1, 11))
        else:
            self.na = self.agent_setting
            self.ne = self.enemy_setting

        cells = [(r, c) for r in range(GRID) for c in range(GRID)]
        self.np_random.shuffle(cells)

        self.agents = np.array(cells[:self.na], dtype=int)
        self.enemies = np.array(
            cells[self.na:self.na + self.ne], dtype=int
        )
        self.steps = 0
        self.tags = 0
        return self.get_obs(), {}

    def get_obs(self):
        obs = np.full(43, -1, dtype=np.float32)
        obs[:2*self.na] = self.agents.flatten() / 9 * 2 - 1
        obs[20:20+2*self.ne] = self.enemies.flatten() / 9 * 2 - 1
        obs[40] = self.na / 10
        obs[41] = self.ne / 10
        obs[42] = self.steps / self.max_steps
        return obs

    def greedy_actions(self, team, opponents):
        actions = []
        for p in team:
            target = min(opponents, key=lambda q: distance(p, q))
            distances = [
                distance(clip_pos(p + move), target) for move in MOVES
            ]
            best_distance = min(distances)
            choices = [
                i for i, d in enumerate(distances)
                if d == best_distance
            ]
            actions.append(int(self.np_random.choice(choices)))
        return np.array(actions)

    def step(self, actions):
        old_distance = sum(
            min(distance(a, e) for e in self.enemies)
            for a in self.agents
        )

        # Move friendly agents using selected actions.
        for i in range(self.na):
            self.agents[i] = clip_pos(
                self.agents[i] + MOVES[int(actions[i])]
            )

        # Enemies also move and chase the nearest agent.
        enemy_actions = self.greedy_actions(
            self.enemies, self.agents
        )
        for i in range(self.ne):
            self.enemies[i] = clip_pos(
                self.enemies[i] + MOVES[enemy_actions[i]]
            )

        # Count agent-enemy contacts.
        contacts = sum(
            np.array_equal(a, e)
            for a in self.agents
            for e in self.enemies
        )
        self.tags += int(contacts)

        new_distance = sum(
            min(distance(a, e) for e in self.enemies)
            for a in self.agents
        )

        self.steps += 1
        reward = (old_distance - new_distance) * 0.05
        truncated = self.steps >= self.max_steps

        return (
            self.get_obs(), float(reward), False, truncated,
            {"contacts": int(contacts)}
        )


# Train PPO on this environment.
print("Training PPO controller. Please wait...")
training_env = WarehouseBattle(random_counts=True)

model = PPO(
    "MlpPolicy",
    training_env,
    learning_rate=0.0003,
    n_steps=256,
    batch_size=64,
    n_epochs=5,
    gamma=0.98,
    seed=42,
    verbose=0
)
model.learn(total_timesteps=10000)
print("PPO training finished.")

# Simulation controls
agents_slider = widgets.IntSlider(
    value=5, min=1, max=10, step=1,
    description="Agents:", continuous_update=False
)
enemies_slider = widgets.IntSlider(
    value=5, min=1, max=10, step=1,
    description="Enemies:", continuous_update=False
)
controller_menu = widgets.Dropdown(
    options=["Random", "Greedy", "PPO"],
    value="Greedy", description="Controller:"
)
frames_slider = widgets.IntSlider(
    value=35, min=10, max=50, step=5,
    description="Frames:", continuous_update=False
)
run_button = widgets.Button(
    description="Run Simulation",
    button_style="success",
    icon="play"
)
output_box = widgets.Output()

def run_simulation(_):
    run_button.disabled = True

    with output_box:
        clear_output(wait=True)

        try:
            env = WarehouseBattle(
                agents=agents_slider.value,
                enemies=enemies_slider.value
            )
            env.reset()

            agent_history = [env.agents.copy()]
            enemy_history = [env.enemies.copy()]

            for _ in range(frames_slider.value):
                if controller_menu.value == "Random":
                    actions = np.random.randint(0, 5, MAX_TEAM)

                elif controller_menu.value == "Greedy":
                    actions = np.full(MAX_TEAM, 4, dtype=int)
                    actions[:env.na] = env.greedy_actions(
                        env.agents, env.enemies
                    )

                else:
                    actions, _ = model.predict(
                        env.get_obs(), deterministic=True
                    )
                    actions = np.asarray(actions).reshape(-1)

                _, _, _, done, _ = env.step(actions)

                agent_history.append(env.agents.copy())
                enemy_history.append(env.enemies.copy())

                if done:
                    break

            fig, ax = plt.subplots(figsize=(7, 7))
            ax.set_xlim(-0.5, 9.5)
            ax.set_ylim(9.5, -0.5)
            ax.set_xticks(range(10))
            ax.set_yticks(range(10))
            ax.grid(True, alpha=0.2)
            ax.set_title(
                f"{controller_menu.value} Controller | "
                f"Agents: {env.na} | Enemies: {env.ne}"
            )

            for r in range(GRID):
                for c in range(GRID):
                    ax.add_patch(Rectangle(
                        (c - 0.5, r - 0.5), 1, 1,
                        fill=False, edgecolor="lightgray",
                        linewidth=0.5
                    ))

            agent_plot = ax.scatter(
                [], [], s=160, c="blue",
                edgecolors="black", label="Agents"
            )
            enemy_plot = ax.scatter(
                [], [], s=160, c="red", marker="X",
                label="Enemies"
            )
            frame_text = ax.text(
                0.02, 1.02, "", transform=ax.transAxes
            )
            ax.legend(loc="upper right")

            def update(frame):
                a = agent_history[frame]
                e = enemy_history[frame]

                agent_plot.set_offsets(np.c_[a[:, 1], a[:, 0]])
                enemy_plot.set_offsets(np.c_[e[:, 1], e[:, 0]])
                frame_text.set_text(
                    f"Frame: {frame}/{len(agent_history)-1}"
                )
                return agent_plot, enemy_plot, frame_text

            animation = FuncAnimation(
                fig, update,
                frames=len(agent_history),
                interval=350,
                blit=False,
                repeat=True
            )
            plt.close(fig)
            display(HTML(animation.to_jshtml()))
            print("Simulation complete.")
            print("Agent-enemy contacts:", env.tags)

        except Exception as error:
            print("ERROR:", type(error).__name__, str(error))

        finally:
            run_button.disabled = False

run_button.on_click(run_simulation)

display(widgets.VBox([
    widgets.HTML(
        "<h2>Warehouse Battle Simulation</h2>"
        "<p>Blue = Agents | Red X = Enemies | No obstacles</p>"
    ),
    agents_slider,
    enemies_slider,
    controller_menu,
    frames_slider,
    run_button,
    output_box
]))